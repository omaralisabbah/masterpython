#------------------------------------------------------
# Arithmetic Operators
#---------------------
# [+] Addition
# [-] Subtraction
# [*] Multiplication
# [/] Division
# [%] Modulus
# [**] Exponent
# [//] Floor Division
#------------------------------------------------------


# [+] Addition
print(12 + 31)

print("--------------")

# [-] Subtraction
print(31 - 12)
print(12 - 31)
print(-31 - -12)
print(0.3 - 99.5)

print("--------------")

# [*] Multiplication
print(12 * 5)
print(40 + 12 * 5)
print((40 + 12) * 5)

print("--------------")

# [/] Division
print(60 / 12)
print(int(60 / 12))

print("--------------")

# [%] Modulus
print(8 % 2)  # 0
print(9 % 2)  # 1


# [**] Exponent
print(2 ** 8)
print(2 * 2 * 2 * 2 * 2 * 2 * 2 * 2)

print("--------------")

# [//] Floor Division
print(100//20)  # 5
print(110//20)  # 5
print(120//20)  # 6
print(546//10)  # 6