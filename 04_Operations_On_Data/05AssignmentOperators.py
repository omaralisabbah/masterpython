# [=] Assignment
x = 10
y = 212

z = x + y
print(z)

x += y
print(x)

print("---------")

x -= y
print(x)

print("---------")

x *= y
print(x)

print("---------")

x /= y
print(x)

print("---------")

x **= y
print(x)

print("---------")

x //= y
print(x)

print("---------")

x %= y
print(x)
