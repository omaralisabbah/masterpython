#------------------------------------------------------
# Comparison Operators
#---------------------
# [ == ] Equal
# [ != ] Not Equal
# [ > ] Greater Than
# [ < ] Less Than
# [ >= ] Greater Than or Equal
# [ <= ] Less Than or Equal
#------------------------------------------------------


# [==] Equal
print(99 == 99)
print(99.99 == 99.99)

print("----------")

# [!=] Equal
print(99 != 100)
print(99.99 != 99.99)

print("----------")

# [>] Greater Than
print(99 > 99)
print(99.99 > 99.999)

print("----------")

# [<] Less Than
print(99 < 99)
print(99.99 < 99.999)

print("----------")

# [>=] Greater Than or Equal
print(99 >= 99)
print(99.99 >= 99.999)

print("----------")

# [<=] Less Than or Equal
print(99 <= 99)
print(99.99 <= 99.999)

print("----------")